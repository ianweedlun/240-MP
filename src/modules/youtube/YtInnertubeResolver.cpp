namespace {
using PlayerEndpoint = InnertubeEndpoints::Player;
using PlayerReply    = InnertubeReply<InnertubeEndpoints::Player>;

// yt-dlp's visionos UA (youtube/_base.py). A Safari UA, not an app UA.
const QString kVisionOsUserAgent = QStringLiteral(
    "Mozilla/5.0 (Macintosh; Intel Mac OS X 15_7_3) AppleWebKit/605.1.15 "
    "(KHTML, like Gecko) Version/26.0 Safari/605.1.15");
}

YtInnertubeResolver::YtInnertubeResolver(QObject *parent)
    : QObject(parent)
{
    m_timeout = new QTimer(this);
    m_timeout->setSingleShot(true);
    connect(m_timeout, &QTimer::timeout, this, [this]() {
        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.ok = false;
        r.reason = QStringLiteral("timeout");
        r.elapsedMs = m_timer.elapsed();
        emitResult(r);
    });
}

void YtInnertubeResolver::ensureClient()
{
    if (m_clientReady)
        return;
    m_clientReady = true;
    if (!m_it)
        m_it = InnerTube::instance();
    // VISIONOS — yt-dlp's JS-less default client. Values copied from yt-dlp's
    // youtube/_base.py INNERTUBE_CLIENTS, not guessed: an app-style UA or an
    // older clientVersion gets LOGIN_REQUIRED ("confirm you're not a bot").
    //
    // Why not IOS: IOS mints URLs that 403 on an open-ended `Range: bytes=0-`,
    // which is exactly what ffmpeg/mpv sends. They only answer bounded ranges,
    // so a curl probe passes while every real playback fails. VISIONOS URLs
    // return 200 bare / 206 open-ended. Gate = mpv decode, not curl.
    //
    // visitorData is generated by the InnertubeClient ctor and sent as
    // X-Goog-Visitor-Id by BaseEndpoint; without it VISIONOS is bot-walled.
    InnertubeClient c(InnertubeClient::ClientType::VISIONOS,
                      QStringLiteral("1.02"));
    c.userAgent = kVisionOsUserAgent;
    c.deviceMake = QStringLiteral("Apple");
    c.deviceModel = QStringLiteral("RealityDevice17,1");
    c.osName = QStringLiteral("visionOS");
    c.osVersion = QStringLiteral("26.5.23O471");
    // Must be page-derived: the ctor's generateVisitorData() is synthetic and
    // YouTube answers LOGIN_REQUIRED for it.
    if (!m_visitorData.isEmpty())
        c.visitorData = m_visitorData;
    m_it->createClient(c);
}

bool YtInnertubeResolver::resolve(const QString &videoId, const QString &resolution,
                                  const QString &key)
{
    if (m_inFlight || videoId.isEmpty())
        return false;
    m_inFlight = true;
    m_videoId = videoId;
    m_resolution = resolution;
    m_key = key;
    m_maxHeight = ytstream::maxHeightForResolution(resolution);
    const qint64 generation = ++m_generation;
    m_timer.start();
    m_timeout->start(kTimeoutMs);

    // First resolve waits on the one-time visitorData fetch; the timeout above
    // already covers that wait, so a slow page falls back to yt-dlp.
    if (m_visitorData.isEmpty() && !m_vdDone) {
        m_pendingStart = true;
        fetchVisitorData();
        return true;
    }
    startPlayer();
    return true;
}

void YtInnertubeResolver::fetchVisitorData()
{
    if (m_vdStarted)
        return;
    m_vdStarted = true;
    auto *nam = new QNetworkAccessManager(this);
    QNetworkRequest req(QUrl(QStringLiteral("https://www.youtube.com/")));
    req.setHeader(QNetworkRequest::UserAgentHeader, kVisionOsUserAgent);
    QNetworkReply *reply = nam->get(req);
    connect(reply, &QNetworkReply::finished, this, [this, reply]() {
        const QByteArray body = reply->readAll();
        reply->deleteLater();
        static const QRegularExpression re(QStringLiteral("\"visitorData\":\"([^\"]+)\""));
        const auto m = re.match(QString::fromUtf8(body));
        if (m.hasMatch())
            m_visitorData = m.captured(1);
        m_vdDone = true;   // even on failure: don't retry per resolve
        if (m_pendingStart) {
            m_pendingStart = false;
            startPlayer();
        }
    });
}

void YtInnertubeResolver::startPlayer()
{
    ensureClient();
    const qint64 generation = m_generation;

    PlayerReply *reply = nullptr;
    try {
        reply = m_it->get<PlayerEndpoint>(m_videoId);
    } catch (const InnertubeException &ex) {
        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.ok = false;
        r.reason = QStringLiteral("exception:") + ex.message();
        r.elapsedMs = m_timer.elapsed();
        emitResult(r);
        return;
    }

    connect(reply, &PlayerReply::finished, this,
            [this, generation](const PlayerEndpoint &player) {
        if (generation != m_generation)
            return; // a timeout already reported this attempt
        m_timeout->stop();

        const InnertubeObjects::StreamingData &sd = player.response.streamingData;
        QVector<ytstream::Format> formats;
        formats.reserve(sd.formats.size() + sd.adaptiveFormats.size());
        for (const InnertubeObjects::StreamingFormat &f : sd.formats)
            formats.append({f.itag, f.height, f.mimeType, f.url, f.audioTrackId,
                            f.audioTrackDisplayName, f.audioIsDefault});
        for (const InnertubeObjects::StreamingFormat &f : sd.adaptiveFormats)
            formats.append({f.itag, f.height, f.mimeType, f.url, f.audioTrackId,
                            f.audioTrackDisplayName, f.audioIsDefault});

        const ytstream::Pair pair = ytstream::selectPair(formats, m_maxHeight);

        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.elapsedMs = m_timer.elapsed();
        if (!pair.ok) {
            r.reason = QStringLiteral("no-playable-pair");
            emitResult(r);
            return;
        }

        qint64 expire = yturl::expireEpochFromUrl(pair.videoUrl);
        if (!pair.audioUrl.isEmpty()) {
            const qint64 audioExpire = yturl::expireEpochFromUrl(pair.audioUrl);
            if (audioExpire > 0 && (expire <= 0 || audioExpire < expire))
                expire = audioExpire;
        }
        const qint64 now = QDateTime::currentSecsSinceEpoch();
        expire = ytstream::expiryEpoch(expire, now, sd.expiresInSeconds.toInt());
        if (expire <= now) {
            r.reason = QStringLiteral("no-expiry");
            emitResult(r);
            return;
        }

        r.videoUrl = pair.videoUrl;
        r.audioUrl = pair.audioUrl;
        r.single = pair.single;
        r.ok = true;
        r.expireEpoch = expire;
        emitResult(r);
    });

    connect(reply, &PlayerReply::exception, this,
            [this, generation](const InnertubeException &ex) {
        if (generation != m_generation)
            return;
        m_timeout->stop();
        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.ok = false;
        r.reason = QStringLiteral("exception:") + ex.message();
        r.elapsedMs = m_timer.elapsed();
        emitResult(r);
    });
}

void YtInnertubeResolver::emitResult(const YtResolveResult &result)
{
    ++m_generation;    // invalidate any reply still in flight
    m_inFlight = false;
    m_timeout->stop();
    emit finished(result);
}
