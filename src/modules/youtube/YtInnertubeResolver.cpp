namespace {
using PlayerEndpoint = InnertubeEndpoints::Player;
using PlayerReply    = InnertubeReply<InnertubeEndpoints::Player>;

// yt-dlp's visionos UA (youtube/_base.py). A Safari UA, not an app UA.
const QString kVisionOsUserAgent = QStringLiteral(
    "Mozilla/5.0 (Macintosh; Intel Mac OS X 15_7_3) AppleWebKit/605.1.15 "
    "(KHTML, like Gecko) Version/26.0 Safari/605.1.15");

// visitorData streaming scan (MEM-02 policy, torture-t0/mem02-policy.md):
// bounded reads + a carry window so a token straddling a chunk boundary is
// still found. Carry >= longest token + 2x literal key + quote slack:
// observed token 450 chars, key literal 15 bytes -> 4096 leaves ~9x headroom.
constexpr int kVdChunkBytes = 65536;
constexpr int kVdCarryBytes = 4096;
const QRegularExpression kVisitorDataRe(QStringLiteral("\"visitorData\":\"([^\"]+)\""));
}

YtInnertubeResolver::YtInnertubeResolver(QObject *parent)
    : QObject(parent)
{
    m_timeout = new QTimer(this);
    m_timeout->setSingleShot(true);
    connect(m_timeout, &QTimer::timeout, this, [this]() {
        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.ok = false;
        r.reason = QStringLiteral("timeout");
        r.elapsedMs = m_timer.elapsed();
        emitResult(r);
    });
}

void YtInnertubeResolver::ensureClient()
{
    if (m_clientReady)
        return;
    m_clientReady = true;
    if (!m_it)
        m_it = InnerTube::instance();
    // VISIONOS — yt-dlp's JS-less default client. Values copied from yt-dlp's
    // youtube/_base.py INNERTUBE_CLIENTS, not guessed: an app-style UA or an
    // older clientVersion gets LOGIN_REQUIRED ("confirm you're not a bot").
    //
    // Why not IOS: IOS mints URLs that 403 on an open-ended `Range: bytes=0-`,
    // which is exactly what ffmpeg/mpv sends. They only answer bounded ranges,
    // so a curl probe passes while every real playback fails. VISIONOS URLs
    // return 200 bare / 206 open-ended. Gate = mpv decode, not curl.
    //
    // visitorData is generated by the InnertubeClient ctor and sent as
    // X-Goog-Visitor-Id by BaseEndpoint; without it VISIONOS is bot-walled.
    InnertubeClient c(InnertubeClient::ClientType::VISIONOS,
                      QStringLiteral("1.02"));
    c.userAgent = kVisionOsUserAgent;
    c.deviceMake = QStringLiteral("Apple");
    c.deviceModel = QStringLiteral("RealityDevice17,1");
    c.osName = QStringLiteral("visionOS");
    c.osVersion = QStringLiteral("26.5.23O471");
    // Must be page-derived: the ctor's generateVisitorData() is synthetic and
    // YouTube answers LOGIN_REQUIRED for it.
    if (!m_visitorData.isEmpty())
        c.visitorData = m_visitorData;
    m_it->createClient(c);
}

bool YtInnertubeResolver::resolve(const QString &videoId, const QString &resolution,
                                  const QString &key)
{
    if (m_inFlight || videoId.isEmpty())
        return false;
    m_inFlight = true;
    m_videoId = videoId;
    m_resolution = resolution;
    m_key = key;
    m_maxHeight = ytstream::maxHeightForResolution(resolution);
    const qint64 generation = ++m_generation;
    m_timer.start();
    m_timeout->start(kTimeoutMs);

    // First resolve waits on the one-time visitorData fetch; the timeout above
    // already covers that wait, so a slow page falls back to yt-dlp.
    if (m_visitorData.isEmpty() && !m_vdDone) {
        m_pendingStart = true;
        // Carry this attempt's generation into the fetch continuation: the
        // timeout abandons an attempt by bumping m_generation, and the late
        // completion must not chain Player for an abandoned attempt (ROB-07).
        m_pendingGeneration = generation;
        fetchVisitorData();
        return true;
    }
    startPlayer(generation);
    return true;
}

void YtInnertubeResolver::fetchVisitorData()
{
    if (m_vdStarted)
        return;
    m_vdStarted = true;
    m_vdBuf = QByteArray();
    m_vdBytes = 0;
    auto *nam = new QNetworkAccessManager(this);
    QNetworkRequest req(QUrl(QStringLiteral("https://www.youtube.com/")));
    req.setHeader(QNetworkRequest::UserAgentHeader, kVisionOsUserAgent);
    QNetworkReply *reply = nam->get(req);
    connect(reply, &QNetworkReply::readyRead, this, [this, reply]() {
        drainVisitorData(reply);
    });
    connect(reply, &QNetworkReply::finished, this, [this, reply]() {
        reply->deleteLater();
        if (m_vdDone)
            return;                 // token/cap already terminal in drain
        drainVisitorData(reply);    // final burst, if any (also on error)
        if (m_vdDone)
            return;
        m_vdDone = true;            // EOF-no-token or error: don't retry per resolve
        if (m_pendingStart) {
            m_pendingStart = false;
            // Generation invariant: only the still-live waiting attempt may
            // chain into Player. A timeout bumped m_generation and already
            // emitted the terminal result, so a stale completion is dropped
            // silently — never emitResult, never issue a Player request.
            if (m_pendingGeneration == m_generation)
                startPlayer(m_pendingGeneration);
        }
    });
}

// Bounded streaming scan of the homepage reply. Consumes at most
// kVdChunkBytes per read into a rolling window (carry + chunk, bounded by
// kVdChunkBytes + kVdCarryBytes), enforcing the inclusive kMaxHomepageBytes
// cap on cumulative delivered bytes BEFORE any QString conversion. Never
// materializes the whole page. Terminal paths: token found (early exit),
// cap exceeded (clean failure into the backend's yt-dlp ladder), or return
// with m_vdDone unset so finished() applies EOF/error semantics.
void YtInnertubeResolver::drainVisitorData(QNetworkReply *reply)
{
    if (m_vdDone)
        return;
    while (reply->bytesAvailable() > 0) {
        const QByteArray chunk = reply->read(kVdChunkBytes);
        if (chunk.isEmpty())
            break;
        m_vdBytes += chunk.size();
        if (m_vdBytes > kMaxHomepageBytes) {
            m_vdDone = true;   // sticky: an oversized page is a server-side condition
            qWarning("[Youtube] visitorData homepage exceeded size cap (bytes=%lld cap=%lld)",
                     static_cast<long long>(m_vdBytes),
                     static_cast<long long>(kMaxHomepageBytes));
            m_vdBuf = QByteArray();
            m_vdBytes = 0;
            if (reply->isRunning())
                reply->abort();   // frees QNAM buffers; finished() is guarded by m_vdDone
            if (m_pendingStart) {
                m_pendingStart = false;
                YtResolveResult r;
                r.videoId = m_videoId;
                r.resolution = m_resolution;
                r.key = m_key;
                r.ok = false;
                r.reason = QStringLiteral("visitordata-size-cap");
                r.elapsedMs = m_timer.elapsed();
                emitResult(r);
            }
            return;
        }
        m_vdBuf.append(chunk);
        const auto m = kVisitorDataRe.match(QString::fromUtf8(m_vdBuf));
        if (m.hasMatch()) {
            m_visitorData = m.captured(1);
            m_vdDone = true;
            m_vdBuf = QByteArray();
            m_vdBytes = 0;
            if (reply->isRunning())
                reply->abort();   // early exit: stop downloading the homepage
            if (m_pendingStart && m_pendingGeneration == m_generation) {
                m_pendingStart = false;
                startPlayer(m_pendingGeneration);
            }
            return;
        }
        if (m_vdBuf.size() > kVdCarryBytes)
            m_vdBuf = m_vdBuf.right(kVdCarryBytes);
    }
}

void YtInnertubeResolver::startPlayer(qint64 generation)
{
    ensureClient();
    // `generation` is the originating attempt's, passed in by the caller.
    // Re-reading m_generation here would bind a late continuation to whatever
    // attempt is current and defeat the timeout invalidation (ROB-07).

    PlayerReply *reply = nullptr;
    try {
        reply = m_it->get<PlayerEndpoint>(m_videoId);
    } catch (const InnertubeException &ex) {
        // Same generation invariant as the async reply handlers: an attempt
        // abandoned while get() ran already has its terminal result.
        if (generation != m_generation)
            return;
        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.ok = false;
        r.reason = QStringLiteral("exception:") + ex.message();
        r.elapsedMs = m_timer.elapsed();
        emitResult(r);
        return;
    }

    connect(reply, &PlayerReply::finished, this,
            [this, generation](const PlayerEndpoint &player) {
        // Generation invariant: this reply must belong to the live attempt.
        // A timeout (or a superseding resolve) bumped m_generation, so a
        // stale reply is dropped — the abandoned attempt already terminated.
        if (generation != m_generation)
            return;
        m_timeout->stop();

        const InnertubeObjects::StreamingData &sd = player.response.streamingData;
        QVector<ytstream::Format> formats;
        formats.reserve(sd.formats.size() + sd.adaptiveFormats.size());
        for (const InnertubeObjects::StreamingFormat &f : sd.formats)
            formats.append({f.itag, f.height, f.mimeType, f.url, f.audioTrackId,
                            f.audioTrackDisplayName, f.audioIsDefault});
        for (const InnertubeObjects::StreamingFormat &f : sd.adaptiveFormats)
            formats.append({f.itag, f.height, f.mimeType, f.url, f.audioTrackId,
                            f.audioTrackDisplayName, f.audioIsDefault});

        const ytstream::Pair pair = ytstream::selectPair(formats, m_maxHeight);

        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.elapsedMs = m_timer.elapsed();
        if (!pair.ok) {
            r.reason = QStringLiteral("no-playable-pair");
            emitResult(r);
            return;
        }

        qint64 expire = yturl::expireEpochFromUrl(pair.videoUrl);
        if (!pair.audioUrl.isEmpty()) {
            const qint64 audioExpire = yturl::expireEpochFromUrl(pair.audioUrl);
            if (audioExpire > 0 && (expire <= 0 || audioExpire < expire))
                expire = audioExpire;
        }
        const qint64 now = QDateTime::currentSecsSinceEpoch();
        expire = ytstream::expiryEpoch(expire, now, sd.expiresInSeconds.toInt());
        if (expire <= now) {
            r.reason = QStringLiteral("no-expiry");
            emitResult(r);
            return;
        }

        r.videoUrl = pair.videoUrl;
        r.audioUrl = pair.audioUrl;
        r.single = pair.single;
        r.ok = true;
        r.expireEpoch = expire;
        emitResult(r);
    });

    connect(reply, &PlayerReply::exception, this,
            [this, generation](const InnertubeException &ex) {
        // Generation invariant: same as the finished handler above — a stale
        // exception from an abandoned attempt must not emit a second result.
        if (generation != m_generation)
            return;
        m_timeout->stop();
        YtResolveResult r;
        r.videoId = m_videoId;
        r.resolution = m_resolution;
        r.key = m_key;
        r.ok = false;
        r.reason = QStringLiteral("exception:") + ex.message();
        r.elapsedMs = m_timer.elapsed();
        emitResult(r);
    });
}

void YtInnertubeResolver::emitResult(const YtResolveResult &result)
{
    // One-terminal-per-attempt latch: m_inFlight is true exactly between an
    // accepted resolve() and its terminal result. Any stale continuation that
    // still reaches here (e.g. a timeout event queued behind a Player result)
    // is dropped, making emitResult idempotent per attempt.
    if (!m_inFlight)
        return;
    ++m_generation;    // invalidate any reply still in flight
    m_inFlight = false;
    m_timeout->stop();
    emit finished(result);
}
