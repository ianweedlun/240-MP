#!/usr/bin/env python3
"""Generate the Consumer Control drain test include from the real source.

The regression test needs to exercise the shipped onConsumerControlReadable()
body, not a paraphrase of it. This script lifts the two functions (the drain
slot and its digit helper) out of src/input/InputManager.cpp by brace matching,
plus the file-scope constants they reference, and writes a generated include
that the test compiles. When the product fix lands, the test picks it up with
no test-side edit.
"""
import pathlib
import re
import sys

DRAIN_SIG = "void InputManager::onConsumerControlReadable()"
DIGIT_SIG = "int InputManager::qtDigitForEvdevCode(int code)"


def extract_function(src, signature):
    start = src.index(signature)
    brace = src.index("{", start)
    depth = 0
    for i in range(brace, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
    raise ValueError("unbalanced braces for " + signature)


def referenced_constants(src, bodies):
    names = set(re.findall(r"\bk[A-Z][A-Za-z0-9]*\b", bodies))
    names.add("kEvdevKeyBase")
    found = []
    for match in re.finditer(r"^\s*(?:constexpr|static\s+const)\s+[^;]*?\b([A-Za-z_]\w*)\s*=[^;]*;",
                             src, re.MULTILINE):
        name, line = match.group(1), match.group(0).strip()
        if name in names and line not in found:
            found.append(line)
    return found


def main(argv):
    source = pathlib.Path(argv[1]).read_text(encoding="utf-8")
    drain = extract_function(source, DRAIN_SIG)
    digit = extract_function(source, DIGIT_SIG)
    bodies = drain + "\n" + digit
    constants = referenced_constants(source, bodies)

    out = [
        "// GENERATED by extract_consumer_ctrl_drain.py — do not edit.",
        "// Source: src/input/InputManager.cpp (verbatim function bodies).",
        "",
    ]
    out.extend(constants)
    out.extend(["", drain, "", digit, ""])
    pathlib.Path(argv[2]).write_text("\n".join(out), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
