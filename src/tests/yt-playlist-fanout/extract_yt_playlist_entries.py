#!/usr/bin/env python3
"""Generate the GREEN-side include from the shipped YouTubeBackend sources.

The fanout gate compiles the real readPlaylistEntries() and
playlistIdFromToken() bodies, not a paraphrase. This lifts both functions and
the four caps they depend on out of the product tree by brace matching, so a
regression in the product (QSet -> QStringList, cap removed, budget changed)
changes what the gate compiles. Missing signatures are a hard error: a gate
that silently compiles stale text is worse than no gate.
"""
import pathlib
import re
import sys

TOKEN_SIG = "static QString playlistIdFromToken(QString token)"
READ_SIG = ("QList<YouTubeBackend::PlaylistFileRef> "
            "YouTubeBackend::readPlaylistEntries(QString *error) const")
CONSTANTS = ("kMaxPlaylistFileIds", "kMaxRetainedPlaylistRows",
             "kMaxPlaylistItems", "kMaxConcurrentPlaylistFetches")


def extract_function(src, signature):
    start = src.find(signature)
    if start < 0:
        raise ValueError("product signature not found: " + signature)
    brace = src.find("{", start)
    if brace < 0:
        raise ValueError("no body for: " + signature)
    depth = 0
    for i in range(brace, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
    raise ValueError("unbalanced braces for " + signature)


def extract_constants(header):
    lines = []
    for name in CONSTANTS:
        pattern = re.compile(
            r"^\s*static\s+constexpr\s+int\s+" + re.escape(name) +
            r"\s*=\s*[^;]+;", re.MULTILINE)
        match = pattern.search(header)
        if not match:
            raise ValueError("product constant not found: " + name)
        lines.append(match.group(0).strip())
    return lines


def main(argv):
    cpp = pathlib.Path(argv[1]).read_text(encoding="utf-8")
    header = pathlib.Path(argv[2]).read_text(encoding="utf-8")
    out_path = pathlib.Path(argv[3])

    token = extract_function(cpp, TOKEN_SIG)
    read = extract_function(cpp, READ_SIG)
    constants = extract_constants(header)

    out = ["// GENERATED by extract_yt_playlist_entries.py - do not edit.",
           "// Verbatim product text: src/modules/youtube/YouTubeBackend.{cpp,h}.",
           ""]
    out.extend(constants)
    out.extend(["", token, "", read, ""])
    out_path.write_text("\n".join(out), encoding="utf-8")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv))
    except (ValueError, IndexError, OSError) as exc:
        print("yt-playlist-fanout extraction failed: " + str(exc), file=sys.stderr)
        sys.exit(1)
